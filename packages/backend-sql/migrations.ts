// Column types per dialect: Postgres gets real booleans, jsonb and timestamptz; SQLite stores
// booleans as 0/1, JSON as text and dates as ISO text. The query code is the same for both.
function types(dialect: SqlDialectName) {
  const pg = dialect === "postgres";
  return {
    bool: pg ? "boolean" : "integer",
    json: pg ? "jsonb" : "text",
    time: pg ? "timestamptz" : "text",
    now: pg ? sql`now()` : sql`(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))`,
    false_: pg ? sql`false` : sql`0`,
    true_: pg ? sql`true` : sql`1`,
    empty_object: pg ? sql`'{}'::jsonb` : sql`'{}'`,
    empty_array: pg ? sql`'[]'::jsonb` : sql`'[]'`,
  };
}

